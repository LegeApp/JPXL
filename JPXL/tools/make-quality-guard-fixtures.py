#!/usr/bin/env python3
"""Deterministic generator for the JPXL "quality-guard" corpus (PR 0).

The quality-guard corpus feeds the perceptual quality controller work. It mixes
adversarial synthetic content (text, line art, gradients, saturated colour,
tiny crops) with derivatives (low-light noise, grayscale) and real project
photographs, split into calibration / development / locked-holdout so no source
family straddles two splits.

Outputs live under ``test-set/quality-guard/`` (gitignored, per AGENTS.md §3)
and are described by ``test-set/quality-corpus.json`` — a ``jpxl.codec-corpus/1``
manifest consumed by ``JPXL/tools/codec_compare.py``.

The harness (`load_manifest` in codec_compare.py) reads each image's ``path`` as
a **binary RGB PPM (P6)** with maxval 255 or 65535 and hashes it, so every
manifest entry points at a ``.ppm`` file. Synthetic/derived fixtures also get a
canonical 8-bit (or 16-bit) sRGB PNG next to the PPM. Every fixture carries a
JSON provenance sidecar (AGENTS.md §9): source/parent + sha256 + transform for
derivatives, generator version + seed for synthetics.

Determinism: all randomness flows through ``numpy`` PRNGs seeded per fixture and
a fixed ``GENERATOR_VERSION``. The PPM raster is fully deterministic and is the
authority for the ``build --check`` idempotency test; PNG bytes are compared too
but only warned on (they can drift across Pillow/zlib versions).

Usage::

    python3 JPXL/tools/make-quality-guard-fixtures.py build
    python3 JPXL/tools/make-quality-guard-fixtures.py build --check
    python3 JPXL/tools/make-quality-guard-fixtures.py list

`build` writes fixtures + manifest. `build --check` regenerates in memory and
compares sha256 against what is on disk (fails on any PPM mismatch). `list`
prints the planned fixture table without touching disk.
"""

