def size_bucket(w: int, h: int) -> str:
    n = w * h
    if n < 256 * 256:
        return "tiny"
    if n <= 1024 * 1024:
        return "small"
    if n <= 3_000_000:
        return "medium"
    if n <= 12_000_000:
        return "large"
    return "xlarge"


def sidecar_for(fx: Fixture, ppm_sha: str, png_sha: str | None) -> dict[str, Any]:
    w, h, depth = fx.dims()
    doc: dict[str, Any] = {
        "schema": SIDECAR_SCHEMA,
        "id": fx.fixture_id,
        "class": fx.klass,
        "split": fx.split,
        "kind": fx.kind,
        "width": w,
        "height": h,
        "bit_depth": depth,
        "license": fx.license,
        "provenance": fx.provenance,
        "ppm": {"path": fx.ppm_rel(), "sha256": ppm_sha, "maxval": 255 if depth == 8 else 65535},
        "regenerate": f"python3 JPXL/tools/{GENERATOR} build",
        "check": f"python3 JPXL/tools/{GENERATOR} build --check",
    }
    if png_sha is not None:
        doc["png"] = {"path": fx.png_rel(), "sha256": png_sha}
    if fx.kind == "synthetic":
        doc["generator"] = {"tool": GENERATOR, "version": GENERATOR_VERSION, "seed": fx.seed}
    if fx.parent is not None:
        doc["parent"] = fx.parent
        doc["transform"] = fx.transform
        if fx.seed is not None:
            doc["generator"] = {"tool": GENERATOR, "version": GENERATOR_VERSION, "seed": fx.seed}
    if fx.notes:
        doc["notes"] = fx.notes
    return doc


def manifest_entry(fx: Fixture, ppm_sha: str) -> dict[str, Any]:
    w, h, depth = fx.dims()
    return {
        "id": fx.fixture_id,
        "path": fx.ppm_rel(),
        "sha256": ppm_sha,
        "strata": [fx.klass, fx.split, size_bucket(w, h)],
        "split": fx.split,
        "class": fx.klass,
        "kind": fx.kind,
        "bit_depth": depth,
        "license": fx.license,
        "provenance": fx.provenance,
        "sidecar": fx.sidecar_rel(),
    }


def realise(fx: Fixture) -> tuple[bytes, bytes | None]:
    """Return (ppm_bytes, png_bytes|None) for a fixture."""
    arr = fx.array
    ppm = ppm_p6(arr)
    png = png_encode(arr) if fx.write_png else None
    return ppm, png


