def _synth(fid, klass, split, subdir, fn, seed, provenance, notes=None) -> Fixture:
    return Fixture(
        fixture_id=fid, klass=klass, split=split, subdir=subdir, build=fn,
        provenance=provenance, license=SYNTHETIC_LICENSE, kind="synthetic",
        write_png=True, seed=seed, notes=notes,
    )


def _derived(fid, klass, split, subdir, fn, parent_rel, transform, seed=None) -> Fixture:
    parent_sha = sha256_file(REPO_ROOT / parent_rel)
    return Fixture(
        fixture_id=fid, klass=klass, split=split, subdir=subdir, build=fn,
        provenance=f"Derived from {parent_rel} ({transform})",
        license=DERIVED_LICENSE, kind="derived", write_png=True, seed=seed,
        parent={"path": parent_rel, "sha256": parent_sha}, transform=transform,
    )


def _source(fid, klass, split, subdir, src_rel) -> Fixture:
    return Fixture(
        fixture_id=fid, klass=klass, split=split, subdir=subdir,
        build=lambda p=src_rel: load_rgb(p),
        provenance=PHOTO_PROVENANCE, license=PHOTO_LICENSE, kind="source",
        write_png=False,
        parent={"path": src_rel, "sha256": sha256_file(REPO_ROOT / src_rel)},
        transform="decode PNG -> P6 PPM, sRGB 8-bit, no resampling",
    )


