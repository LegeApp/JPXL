def cmd_build(check: bool) -> int:
    fixtures = registry()
    # Duplicate-id guard.
    ids = [f.fixture_id for f in fixtures]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        print(f"ERROR: duplicate fixture ids: {sorted(dupes)}", file=sys.stderr)
        return 2

    manifest_images: list[dict[str, Any]] = []
    ppm_mismatch = 0
    png_mismatch = 0
    written = 0
    for fx in fixtures:
        ppm, png = realise(fx)
        ppm_sha = sha256_bytes(ppm)
        png_sha = sha256_bytes(png) if png is not None else None
        ppm_path = REPO_ROOT / "test-set" / fx.ppm_rel()
        png_path = REPO_ROOT / "test-set" / fx.png_rel()
        side_path = REPO_ROOT / "test-set" / fx.sidecar_rel()
        entry = manifest_entry(fx, ppm_sha)
        manifest_images.append(entry)

        if check:
            if not ppm_path.is_file():
                print(f"MISSING ppm: {fx.ppm_rel()}", file=sys.stderr)
                ppm_mismatch += 1
                continue
            on_disk = sha256_file(ppm_path)
            if on_disk != ppm_sha:
                print(f"PPM MISMATCH {fx.fixture_id}: disk={on_disk} regen={ppm_sha}", file=sys.stderr)
                ppm_mismatch += 1
            if png is not None and png_path.is_file():
                if sha256_file(png_path) != png_sha:
                    print(f"png differs (non-fatal, env-dependent) {fx.fixture_id}", file=sys.stderr)
                    png_mismatch += 1
        else:
            ppm_path.parent.mkdir(parents=True, exist_ok=True)
            ppm_path.write_bytes(ppm)
            if png is not None:
                png_path.write_bytes(png)
            side_path.write_text(
                json.dumps(sidecar_for(fx, ppm_sha, png_sha), indent=2, sort_keys=True) + "\n",
                encoding="utf-8",
            )
            written += 1
        # Free memory for large photos.
        fx._array = None

    manifest = {
        "schema": CORPUS_SCHEMA,
        "generator": {"tool": GENERATOR, "version": GENERATOR_VERSION},
        "description": "JPXL quality-guard corpus (PR 0): calibration/development/locked-holdout "
                       "splits for the perceptual quality controller. Paths are P6 PPM inputs for "
                       "JPXL/tools/codec_compare.py; each has a sibling sidecar and (for synthetic/"
                       "derived fixtures) a canonical PNG.",
        "splits": ["calibration", "development", "holdout"],
        "images": manifest_images,
    }

    if check:
        if ppm_mismatch:
            print(f"CHECK FAILED: {ppm_mismatch} PPM mismatch(es), {png_mismatch} png diff(s)", file=sys.stderr)
            return 1
        # Verify the on-disk manifest matches the regenerated one (ignoring nothing).
        if MANIFEST_PATH.is_file():
            disk_manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
            if disk_manifest.get("images") != manifest_images:
                print("CHECK FAILED: manifest images drifted from regenerated set", file=sys.stderr)
                return 1
        print(f"CHECK OK: {len(fixtures)} fixtures reproduce identical PPM sha256"
              + (f" ({png_mismatch} png byte-diffs, non-fatal)" if png_mismatch else ""))
        return 0

    MANIFEST_PATH.write_text(json.dumps(manifest, indent=2, sort_keys=False) + "\n", encoding="utf-8")
    print(f"wrote {written} fixtures under {CORPUS_DIR}")
    print(f"wrote manifest {MANIFEST_PATH} with {len(manifest_images)} images")
    _print_summary(fixtures)
    return 0


def _print_summary(fixtures: list[Fixture]) -> None:
    from collections import Counter
    by_split = Counter(f.split for f in fixtures)
    by_class = Counter(f.klass for f in fixtures)
    print("\nsplit counts:", dict(by_split))
    print("class counts:", dict(by_class))


def cmd_list() -> int:
    fixtures = registry()
    print(f"{'id':44} {'class':16} {'split':12} {'kind':10}")
    for fx in fixtures:
        print(f"{fx.fixture_id:44} {fx.klass:16} {fx.split:12} {fx.kind:10}")
    _print_summary(fixtures)
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    build = sub.add_parser("build", help="write fixtures + manifest")
    build.add_argument("--check", action="store_true",
                       help="regenerate and compare sha256 instead of writing (idempotency test)")
    sub.add_parser("list", help="print planned fixture table without touching disk")
    args = parser.parse_args(argv)
    if args.command == "build":
        return cmd_build(args.check)
    if args.command == "list":
        return cmd_list()
    parser.error("unknown command")
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
