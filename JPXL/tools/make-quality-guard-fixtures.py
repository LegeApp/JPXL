def build_line_art(width: int, height: int, seed: int, anti_alias: bool) -> np.ndarray:
    rng = np.random.default_rng(seed)
    ss = 4 if anti_alias else 1
    W, H = width * ss, height * ss
    img = Image.new("RGB", (W, H), (250, 250, 248))
    draw = ImageDraw.Draw(img)
    # Circles.
    for _ in range(14):
        cx, cy = int(rng.integers(0, W)), int(rng.integers(0, H))
        r = int(rng.integers(20 * ss, 120 * ss))
        col = tuple(int(c) for c in rng.integers(0, 200, size=3))
        draw.ellipse([cx - r, cy - r, cx + r, cy + r], outline=col, width=max(1, ss))
    # Polygons.
    for _ in range(8):
        n = int(rng.integers(3, 7))
        pts = [(int(rng.integers(0, W)), int(rng.integers(0, H))) for _ in range(n)]
        col = tuple(int(c) for c in rng.integers(0, 200, size=3))
        draw.polygon(pts, outline=col)
    # Thin diagonal line fan.
    for i in range(0, W, 24 * ss):
        draw.line([(i, 0), (0, i)], fill=(40, 40, 40), width=max(1, ss))
    if anti_alias and ss > 1:
        img = img.resize((width, height), Image.LANCZOS)
    return np.asarray(img, dtype=np.uint8).copy()


def build_hatch(width: int, height: int, seed: int) -> np.ndarray:
    rng = np.random.default_rng(seed)
    img = Image.new("RGB", (width, height), (255, 255, 255))
    draw = ImageDraw.Draw(img)
    spacing = 6
    for x in range(-height, width, spacing):
        draw.line([(x, 0), (x + height, height)], fill=(20, 20, 20), width=1)
    for x in range(0, width + height, spacing * 2):
        draw.line([(x, 0), (x - height, height)], fill=(90, 90, 90), width=1)
    # A few solid reference squares to mix flat and hatched regions.
    for _ in range(5):
        x0 = int(rng.integers(0, width - 120))
        y0 = int(rng.integers(0, height - 120))
        col = tuple(int(c) for c in rng.integers(0, 255, size=3))
        draw.rectangle([x0, y0, x0 + 100, y0 + 100], fill=col)
    return np.asarray(img, dtype=np.uint8).copy()


def build_gradient(width: int, height: int, mode: str, seed: int, depth: int = 8) -> np.ndarray:
    rng = np.random.default_rng(seed)
    yy, xx = np.mgrid[0:height, 0:width].astype(np.float64)
    if mode == "horizontal":
        t = xx / max(1, width - 1)
        r, g, b = t, 0.5 * np.ones_like(t), 1.0 - t
    elif mode == "vertical":
        t = yy / max(1, height - 1)
        r, g, b = 0.2 + 0.6 * t, t, 0.9 - 0.5 * t
    elif mode == "radial":
        cx, cy = width / 2.0, height / 2.0
        d = np.sqrt((xx - cx) ** 2 + (yy - cy) ** 2)
        t = d / d.max()
        r, g, b = 1.0 - t, 0.3 + 0.4 * t, t
    elif mode == "sky":
        # Low-amplitude near-blue sky ramp with slight noise (banding stress).
        t = yy / max(1, height - 1)
        r = 0.42 + 0.06 * t
        g = 0.58 + 0.05 * t
        b = 0.80 - 0.04 * t
        noise = rng.normal(0.0, 1.2 / 255.0, size=(height, width))
        r, g, b = r + noise, g + noise, b + noise
    else:
        raise ValueError(f"unknown gradient mode {mode}")
    rgb = np.clip(np.stack([r, g, b], axis=-1), 0.0, 1.0)
    if depth == 16:
        return np.rint(rgb * 65535.0).astype(np.uint16)
    return to_u8(rgb * 255.0)


def build_saturated(width: int, height: int, seed: int, soft: bool) -> np.ndarray:
    primaries = [
        (255, 0, 0), (0, 255, 0), (0, 0, 255),
        (0, 255, 255), (255, 0, 255), (255, 255, 0),
        (255, 255, 255), (0, 0, 0),
    ]
    cols = 4
    rows = 2
    cw, ch = width // cols, height // rows
    arr = np.zeros((height, width, 3), dtype=np.uint8)
    for idx, color in enumerate(primaries):
        rr, cc = divmod(idx, cols)
        y0, x0 = rr * ch, cc * cw
        arr[y0 : y0 + ch, x0 : x0 + cw] = color
    if soft:
        blurred = np.asarray(
            Image.fromarray(arr).filter(
                __import__("PIL.ImageFilter", fromlist=["GaussianBlur"]).GaussianBlur(3.5)
            ),
            dtype=np.uint8,
        )
        arr = blurred.copy()
    return arr


def crop(arr: np.ndarray, w: int, h: int, ox: int, oy: int) -> np.ndarray:
    H, W, _ = arr.shape
    ox = max(0, min(ox, W - w))
    oy = max(0, min(oy, H - h))
    return np.ascontiguousarray(arr[oy : oy + h, ox : ox + w])


def build_grayscale(arr: np.ndarray) -> np.ndarray:
    lin = srgb_to_linear(arr.astype(np.float64) / 255.0)
    y = 0.2126 * lin[..., 0] + 0.7152 * lin[..., 1] + 0.0722 * lin[..., 2]
    srgb = linear_to_srgb(y)
    g = to_u8(srgb * 255.0)
    return np.repeat(g[..., None], 3, axis=2)


def build_lowlight(arr: np.ndarray, seed: int) -> np.ndarray:
    rng = np.random.default_rng(seed)
    lin = srgb_to_linear(arr.astype(np.float64) / 255.0) * 0.25
    scale = 500.0  # photon-count scale for Poisson shot noise
    shot = rng.poisson(np.clip(lin, 0.0, None) * scale) / scale
    read = rng.normal(0.0, 0.006, size=lin.shape)  # sensor read noise (linear)
    noisy = np.clip(shot + read, 0.0, 1.0)
    return to_u8(linear_to_srgb(noisy) * 255.0)


