def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def ppm_p6(arr: np.ndarray) -> bytes:
    """Encode an HxWx3 uint8/uint16 array as a binary P6 PPM (big-endian)."""
    if arr.ndim != 3 or arr.shape[2] != 3:
        raise ValueError(f"expected HxWx3 array, got {arr.shape}")
    height, width, _ = arr.shape
    if arr.dtype == np.uint8:
        maxval = 255
        body = np.ascontiguousarray(arr).tobytes()
    elif arr.dtype == np.uint16:
        maxval = 65535
        body = np.ascontiguousarray(arr.astype(">u2")).tobytes()
    else:
        raise ValueError(f"unsupported dtype {arr.dtype}")
    header = f"P6\n{width} {height}\n{maxval}\n".encode("ascii")
    return header + body


def png_encode(arr: np.ndarray) -> bytes:
    """Deterministically encode HxWx3 uint8 (Pillow) or uint16 (hand-rolled)."""
    if arr.dtype == np.uint8:
        buffer = io.BytesIO()
        Image.fromarray(np.ascontiguousarray(arr)).save(
            buffer, format="PNG", optimize=False, compress_level=6
        )
        return buffer.getvalue()
    if arr.dtype == np.uint16:
        return _png16(arr)
    raise ValueError(f"unsupported dtype {arr.dtype}")


def _png16(arr: np.ndarray) -> bytes:
    """Minimal deterministic 16-bit RGB PNG (colour type 2, bit depth 16)."""
    height, width, _ = arr.shape
    be = np.ascontiguousarray(arr.astype(">u2"))
    rows = bytearray()
    line_bytes = width * 3 * 2
    flat = be.tobytes()
    for y in range(height):
        rows.append(0)  # filter type 0 (None)
        rows.extend(flat[y * line_bytes : (y + 1) * line_bytes])

    def chunk(kind: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data))
            + kind
            + data
            + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)
        )

    sig = b"\x89PNG\r\n\x1a\n"
    ihdr = struct.pack(">IIBBBBB", width, height, 16, 2, 0, 0, 0)
    idat = zlib.compress(bytes(rows), 6)
    return sig + chunk(b"IHDR", ihdr) + chunk(b"IDAT", idat) + chunk(b"IEND", b"")


