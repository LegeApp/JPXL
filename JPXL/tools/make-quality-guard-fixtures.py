@dataclass
class Fixture:
    fixture_id: str
    klass: str
    split: str  # calibration | development | holdout
    subdir: str
    build: Callable[[], np.ndarray]  # returns HxWx3 uint8 or uint16
    provenance: str
    license: str
    kind: str  # synthetic | derived | source
    write_png: bool = True
    seed: int | None = None
    parent: dict[str, Any] | None = None
    transform: str | None = None
    notes: str | None = None
    # Filled during realisation:
    _array: np.ndarray | None = field(default=None, repr=False)

    @property
    def array(self) -> np.ndarray:
        if self._array is None:
            self._array = self.build()
        return self._array

    def dims(self) -> tuple[int, int, int]:
        h, w, _ = self.array.shape
        depth = 8 if self.array.dtype == np.uint8 else 16
        return w, h, depth

    def ppm_rel(self) -> str:
        return f"quality-guard/{self.subdir}/{self.fixture_id}.ppm"

    def png_rel(self) -> str:
        return f"quality-guard/{self.subdir}/{self.fixture_id}.png"

    def sidecar_rel(self) -> str:
        return f"quality-guard/{self.subdir}/{self.fixture_id}.json"


